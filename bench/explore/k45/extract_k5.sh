#!/bin/bash
# K45 gate bundle: copy immerdink's real K5 ('k5fin') device code and its headers, VERBATIM, from one immerdink commit.
# Run on the dev box (git read only; nothing is built):  bash extract_k5.sh [rev, default origin/dev]
# Writes, next to this script:
#   imd/include/immerdink/detail/constants.hpp, imd/src/device/{constants.cuh,modp.hpp,residue.hpp}, imd/src/kernels/numerics.cuh
#       (whole files, unchanged; numerics.cuh has crt_round_fin / finish_f1_fast / sub_limbs; constants.cuh the static __constant__ tables)
#   k5_extract.cuh: five verbatim line ranges of src/contract.cu (found by anchors, never by line number):
#       OutArgs .. store_out | crt_f64_elem | kK5WarpSlots | k5f_vmeta .. k5f_elems | k5f_crt_n
#   K5_SOURCE: the commit, the blob ids and the line ranges.
set -euo pipefail
REPO=${IMMERDINK_REPO:-/home/ef/repos/immerdink}
REV=${1:-origin/dev}
HERE="$(cd "$(dirname "$0")" && pwd)"
SHA="$(git -C "$REPO" rev-parse "$REV^{commit}")"
cd "$HERE"
for f in include/immerdink/detail/constants.hpp src/device/constants.cuh src/device/modp.hpp src/device/residue.hpp src/kernels/numerics.cuh; do
  mkdir -p "imd/$(dirname "$f")"; git -C "$REPO" show "$SHA:$f" > "imd/$f"
done
C="$(mktemp)"; trap 'rm -f "$C"' EXIT
git -C "$REPO" show "$SHA:src/contract.cu" > "$C"
first() { grep -n -m1 -F -- "$1" "$C" | cut -d: -f1; }                         # first line containing a fixed string
first_after() { awk -v s="$2" -v p="$1" 'NR > s && index($0, p) { print NR; exit }' "$C"; }
a1=$(first 'struct OutArgs {');                      b1=$(( $(first_after '// Largest N whose CRT word' "$a1") - 1 ))
a2=$(first 'template <int N, int L, int Mut = 0, bool Fin = false>'); b2=$(( $(first_after '// Planes l .. N-1 for E elements' "$a2") - 1 ))
a3=$(first 'constexpr int kK5WarpSlots = 128 + 8;'); b3=$a3
a4=$(first '__device__ __forceinline__ bool k5f_vmeta(const OutArgs& a)'); b4=$(( $(first_after '// k5fin launch check' "$a4") - 1 ))
a5=$(( $(first 'k5f_crt_n(OutArgs a) {') - 1 ));      b5=$(( $(first 'k5f_crt_bfast(OutArgs a, int lg_tl) {') - 2 ))
for v in a1 b1 a2 b2 a3 a4 b4 a5 b5; do [ -n "${!v}" ] && [ "${!v}" -gt 0 ] || { echo "anchor $v not found" >&2; exit 1; }; done
{
  echo "// GENERATED by extract_k5.sh: verbatim lines of immerdink src/contract.cu at $SHA. Do not edit; re-run the script."
  echo "// Ranges: $a1-$b1 (OutArgs..store_out), $a2-$b2 (crt_f64_elem), $a3 (kK5WarpSlots), $a4-$b4 (k5f_vmeta..k5f_elems), $a5-$b5 (k5f_crt_n)."
  echo "// Context expected by the includer (as in contract.cu): namespace imd::detail { namespace { using imd::device::c_tables;"
  echo "// using namespace imd::kernels; constexpr int kThreads = 256; ... } }"
  for r in "$a1,$b1" "$a2,$b2" "$a3,$b3" "$a4,$b4" "$a5,$b5"; do echo "// ---- contract.cu lines ${r/,/-}"; sed -n "${r}p" "$C"; done
} > k5_extract.cuh
{
  echo "immerdink commit $SHA ($(git -C "$REPO" log -1 --format='%cd %s' "$SHA"))"
  echo "src/contract.cu blob $(git -C "$REPO" rev-parse "$SHA:src/contract.cu") lines $a1-$b1 $a2-$b2 $a3 $a4-$b4 $a5-$b5"
  for f in include/immerdink/detail/constants.hpp src/device/constants.cuh src/device/modp.hpp src/device/residue.hpp src/kernels/numerics.cuh; do
    echo "$f blob $(git -C "$REPO" rev-parse "$SHA:$f")"; done
} > K5_SOURCE
cat K5_SOURCE
