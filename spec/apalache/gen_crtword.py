#!/usr/bin/env python3
"""Generate the Apalache CRT-word modules CRTWord<N>.tla from params_out.json.

The real moduli p_l, P = prod p_l, M_l = P / p_l and L_w come from
spec/params_out.json, which spec/params.py writes (`python3 spec/params.py
--json`); nothing here recomputes them. Every number is re-checked below in
exact integer arithmetic before it is written, so a stale or edited JSON file
cannot produce a module that silently proves the wrong claim.

    python3 spec/apalache/gen_crtword.py           write CRTWord16.tla, CRTWord20.tla
    python3 spec/apalache/gen_crtword.py --check   exit 1 if they are out of date
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PARAMS = os.path.join(HERE, "..", "params_out.json")
NS = (16, 20)

TEMPLATE = r"""------------------------------ MODULE CRTWord{N} ------------------------------
(***************************************************************************)
(* GENERATED by spec/apalache/gen_crtword.py from spec/params_out.json     *)
(* (spec/params.py --json). Do not edit; regenerate.                       *)
(*                                                                         *)
(* DESIGN §3.6 running CRT at the REAL width, N = {N}, L_w = {Lw}         *)
(* (L32 = {L32} u32 limbs), symbolically (Apalache: unbounded SMT ints):   *)
(*                                                                         *)
(*   x <- 0                                                                *)
(*   for l = 1..N:  y <- (q_l W_l) mod p_l      (any value in [0, p_l):    *)
(*                                               q_l is invertible mod p_l *)
(*                                               and W_l ranges over       *)
(*                                               [0, p_l), so every y is   *)
(*                                               reachable)                *)
(*                  x <- x + M_l y;  if x >= P: x <- x - P                 *)
(*                                                                         *)
(* State: l (next modulus), x (the word), y (the digit the next step       *)
(* adds). Claims, proved as an inductive invariant (check.sh runs          *)
(* Init => IndInv, IndInv /\ Next => IndInv', IndInv => Safety):           *)
(*   XBelowP        x < P after every step (so the centering z = x or      *)
(*                  x - P of §3.6 is valid);                               *)
(*   PeakBound      the un-reduced value x + M_l y < 2P;                    *)
(*   NoWordOverflow x + M_l y < 2^L_w: the peak fits the unsigned word     *)
(*                  (2P <= 2^L_w).                                         *)
(* The exact reachable peak (params.py crt_peak_exact, proved there by a   *)
(* formula brute-forced on scaled tables only) is checked here at the real *)
(* width by bounded model checking from Init over all N steps, i.e. over   *)
(* EVERY reachable state:                                                  *)
(*   PeakAtMostCert x + M_l y <= CrtPeak holds (no error), and             *)
(*   PeakBelowCert  x + M_l y <  CrtPeak is VIOLATED (expected): the peak  *)
(*                  is attained. CrtPeak >= 2^(L_w - 32) (WordNarrow,     *)
(*                  constant), so one limb fewer really overflows.        *)
(* Expected violation: XBelowP under NextNoSub (no conditional             *)
(* subtraction).                                                           *)
(***************************************************************************)
EXTENDS Integers

N      == {N}
Lw     == {Lw}
TwoLw  == {TwoLw}        \* 2^{Lw}
TwoLwNarrow == {TwoLwNarrow}  \* 2^{LwNarrow}
CrtPeak == {CrtPeak}
P      == {P}
\* @type: Seq(Int);
Mods   == <<{Mods}>>
\* @type: Seq(Int);
Ms     == <<{Ms}>>

VARIABLES
    \* @type: Int;
    l,
    \* @type: Int;
    x,
    \* @type: Int;
    y

\* The digit for modulus i: y in [0, p_i) (p_i <= 256).
Digit(i, v) == v \in 0..255 /\ (i <= N => v < Mods[i])

Init == l = 1 /\ x = 0 /\ y \in 0..255 /\ Digit(1, y)

Reduce(t) == IF t >= P THEN t - P ELSE t

Next ==
    /\ l <= N
    /\ x' = Reduce(x + Ms[l] * y)
    /\ l' = l + 1
    /\ y' \in 0..255 /\ Digit(l + 1, y')

\* Negative: the conditional subtraction dropped.
NextNoSub ==
    /\ l <= N
    /\ x' = x + Ms[l] * y
    /\ l' = l + 1
    /\ y' \in 0..255 /\ Digit(l + 1, y')

XBelowP        == x < P
PeakBound      == l <= N => x + Ms[l] * y < 2 * P
NoWordOverflow == l <= N => x + Ms[l] * y < TwoLw
WordFits       == 2 * P <= TwoLw
WordNarrow     == TwoLwNarrow <= CrtPeak /\ CrtPeak < 2 * P
Safety         == XBelowP /\ PeakBound /\ NoWordOverflow /\ WordFits /\ WordNarrow
PeakAtMostCert == l <= N => x + Ms[l] * y <= CrtPeak
PeakBelowCert  == l <= N => x + Ms[l] * y < CrtPeak

IndInv ==
    /\ l \in 1..(N + 1)
    /\ x \in 0..(P - 1)
    /\ y \in 0..255
    /\ Digit(l, y)
=============================================================================
"""


def load():
    with open(PARAMS) as f:
        return json.load(f)


def render(js, N):
    d = js["per_N"][str(N)]
    mods = [int(v) for v in d["moduli"]]
    P = int(d["P"])
    Ms = [int(v) for v in d["M"]]
    Lw = int(d["Lw"])
    L32 = int(d["L32"])
    # Re-check everything the module relies on, exactly.
    assert mods == [int(v) for v in js["moduli"]][:N], "moduli prefix"
    assert len(mods) == N and all(2 <= p <= 256 for p in mods)
    assert all(math.gcd(a, b) == 1 for i, a in enumerate(mods) for b in mods[i + 1:])
    assert P == math.prod(mods)
    assert Ms == [P // p for p in mods] and all(P % p == 0 for p in mods)
    assert Lw == 32 * L32
    assert 2 * P <= 2 ** Lw and not 2 * P <= 2 ** (Lw - 32), "L32 minimal"
    peak = int(d["crt_peak"])
    assert 2 ** (Lw - 32) <= peak < 2 * P
    return TEMPLATE.format(
        N=N, Lw=Lw, L32=L32, TwoLw=2 ** Lw, LwNarrow=Lw - 32, CrtPeak=peak,
        TwoLwNarrow=2 ** (Lw - 32), P=P,
        Mods=", ".join(map(str, mods)), Ms=", ".join(map(str, Ms)))


def main():
    check = "--check" in sys.argv[1:]
    js = load()
    stale = []
    for N in NS:
        text = render(js, N)
        path = os.path.join(HERE, f"CRTWord{N}.tla")
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            if check:
                stale.append(path)
            else:
                with open(path, "w") as f:
                    f.write(text)
                print(f"wrote {path}")
    if stale:
        print("out of date (run spec/apalache/gen_crtword.py): " + " ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
